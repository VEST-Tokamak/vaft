#!/usr/bin/env python3
"""Build, validate and publish the VAFT documentation site.

The site has two tracks.  The stable track is built from ``main`` and served at
the root of https://vest-tokamak.github.io/vaft/ ; the development track is
built from ``develop`` and served under ``/develop/``.  Both are composed into a
single tree and published as one commit on the ``gh-pages`` branch, which holds
generated output only.

Each track is built from a *source tree of its own branch*, extracted with
``git archive`` into a temporary directory.  That matters more than it looks:
the documentation includes data generated by introspecting the library, so it
is only correct for the exact tree it was generated from.  Nothing here reads
or writes the caller's checkout, and the branch you happen to be standing on
makes no difference to the result.

    python docs/build.py                      # dry run, both tracks, nothing published
    python docs/build.py --publish            # the same, then one commit on gh-pages
    python docs/build.py --regenerate-only    # refresh _data in this checkout, for a local preview

Publishing is all-or-nothing.  If any track fails to generate, build or
validate, or if the composed tree fails its own checks, ``gh-pages`` is left
exactly as it was.

Exit codes: 0 success, 1 build or validation failure, 2 another publish landed
first, 3 a required tool is missing, 4 the request was refused.
"""

from __future__ import annotations

import argparse
import datetime as _datetime
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

EXIT_OK = 0
EXIT_FAILED = 1
EXIT_RACE = 2
EXIT_TOOLCHAIN = 3
EXIT_REFUSED = 4

SITE_URL = "https://vest-tokamak.github.io"
PUBLISH_BRANCH = "gh-pages"
PROVENANCE_SCHEMA = 1
#: Nothing legitimate approaches this; a runaway ``vendor/`` copy does.
MAX_SITE_MIB = 40


class BuildError(RuntimeError):
    """A step failed.  Nothing has been published."""


class ToolchainError(RuntimeError):
    """A required external tool is missing."""


class PublishRace(RuntimeError):
    """The publish branch moved while this build was running."""


@dataclass(frozen=True)
class TrackSpec:
    """The fixed identity of a documentation track."""

    name: str
    default_ref: str
    prefix: str  # "" for the site root, "develop" for the subdirectory
    baseurl: str
    configs: tuple[str, ...]


TRACKS: dict[str, TrackSpec] = {
    "stable": TrackSpec("stable", "origin/main", "", "/vaft", ("_config.yml",)),
    "development": TrackSpec(
        "development",
        "origin/develop",
        "develop",
        "/vaft/develop",
        ("_config.yml", "_config.develop.yml"),
    ),
}


@dataclass
class Track:
    """A track resolved to a specific commit and, later, an extracted tree."""

    spec: TrackSpec
    ref: str
    commit: str
    commit_date: str
    root: Path | None = None
    site: Path | None = None
    vaft_version: str = ""
    pages: int = 0
    outputs: list[str] = field(default_factory=list)

    @property
    def name(self) -> str:
        return self.spec.name

    @property
    def docs(self) -> Path:
        if self.root is None:
            raise BuildError(f"{self.name}: source tree has not been extracted")
        return self.root / "docs"


# --------------------------------------------------------------------------
# small helpers
# --------------------------------------------------------------------------


def _run(
    command: list[str],
    *,
    cwd: Path | None = None,
    env: dict[str, str] | None = None,
    capture: bool = True,
    check: bool = True,
) -> subprocess.CompletedProcess:
    result = subprocess.run(
        command,
        cwd=None if cwd is None else str(cwd),
        env=env,
        capture_output=capture,
        text=True,
    )
    if check and result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip()
        raise BuildError(f"command failed ({result.returncode}): {' '.join(command)}\n{detail}")
    return result


def _git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return _run(["git", *args], cwd=repo, check=check)


def _require(tool: str) -> None:
    if shutil.which(tool) is None:
        raise ToolchainError(f"{tool!r} is not on PATH")


def _now() -> str:
    return _datetime.datetime.now(_datetime.timezone.utc).replace(microsecond=0).isoformat()


def _load_yaml(path: Path):
    try:
        import yaml
    except ModuleNotFoundError as exc:  # pragma: no cover - depends on the environment
        raise ToolchainError(
            "PyYAML is required by docs/build.py; it ships with vaft, so "
            "`pip install -e .` in the repository root, or `pip install pyyaml`"
        ) from exc
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _dump_yaml(data, path: Path) -> None:
    import yaml

    path.write_text(
        yaml.safe_dump(data, sort_keys=False, allow_unicode=True, default_flow_style=False),
        encoding="utf-8",
    )


#: ``path``/``sha256`` pairs, in either the block style the formula catalog uses
#: or the flow style the diagnostic registry uses.
_SOURCE_PAIR = re.compile(r"path:\s*([^\s,}\]]+)\s*,?\s*sha256:\s*([0-9a-f]{64})")


def _declared_sources(snapshot: Path) -> list[tuple[str, str]]:
    return _SOURCE_PAIR.findall(snapshot.read_text(encoding="utf-8"))


# --------------------------------------------------------------------------
# resolving and extracting the source trees
# --------------------------------------------------------------------------


def resolve_track(spec: TrackSpec, ref: str, repo: Path) -> Track:
    """Pin a track to one commit, so every later step names the same tree."""
    resolved = _git(repo, "rev-parse", "--verify", f"{ref}^{{commit}}").stdout.strip()
    date = _git(repo, "show", "-s", "--format=%cI", resolved).stdout.strip()
    return Track(spec=spec, ref=ref, commit=resolved, commit_date=date)


def export_source(track: Track, destination: Path, repo: Path) -> Path:
    """Extract the track's commit into ``destination``.

    ``git archive`` rather than ``git worktree``: it registers nothing, takes no
    lock, cannot collide with a branch that is already checked out somewhere
    else, and needs no cleanup beyond removing the directory.
    """
    destination.mkdir(parents=True, exist_ok=True)
    archive = destination.parent / f"{track.name}.tar"
    _git(repo, "archive", "--format=tar", "-o", str(archive), track.commit)
    _run(["tar", "-xf", str(archive), "-C", str(destination)])
    archive.unlink()
    if not (destination / "docs").is_dir():
        raise BuildError(
            f"{track.name}: {track.ref} ({track.commit[:7]}) has no docs/ directory. "
            "Both branches must carry the site source before either can be published."
        )
    track.root = destination
    track.vaft_version = _read_version(destination)
    return destination


def _read_version(root: Path) -> str:
    """Read ``vaft.version.__version__`` as text.

    Parsed rather than imported: this is a second copy of the package, and
    importing it would put the wrong ``vaft`` in this interpreter.
    """
    source = (root / "vaft" / "version.py").read_text(encoding="utf-8")
    match = re.search(r'^__version__\s*=\s*["\']([^"\']+)["\']', source, re.M)
    return match.group(1) if match else "unknown"


