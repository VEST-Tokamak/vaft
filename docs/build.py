def compose(tracks: list[Track], destination: Path) -> Path:
    """Lay the tracks out as one publishable tree."""
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)

    for track in tracks:
        target = destination if not track.spec.prefix else destination / track.spec.prefix
        if track.site is None:
            raise BuildError(f"{track.name}: nothing was built")
        shutil.copytree(track.site, target, dirs_exist_ok=True)

    (destination / ".nojekyll").write_text("", encoding="utf-8")
    _dump_yaml(
        {
            "schema_version": PROVENANCE_SCHEMA,
            "generated_at": _now(),
            "generator": "docs/build.py",
            "site": {"url": SITE_URL, "baseurl": "/vaft"},
            "tracks": {
                track.name: {
                    "prefix": "/" + (track.spec.prefix + "/" if track.spec.prefix else ""),
                    "baseurl": track.spec.baseurl,
                    "ref": track.ref,
                    "commit": track.commit,
                    "commit_date": track.commit_date,
                    "vaft_version": track.vaft_version,
                    "pages": track.pages,
                    "generated": track.outputs,
                }
                for track in tracks
            },
        },
        destination / "provenance.yml",
    )
    (destination / "README.md").write_text(
        "# VAFT documentation, published\n\n"
        "This branch is **generated output**. Every file here is written by\n"
        "`docs/build.py` and replaced wholesale on each publish, so an edit made\n"
        "here survives exactly until the next one and reaches nobody's review.\n\n"
        "The source lives in `docs/` on the code branches: the site root is built\n"
        "from `main`, and `/develop/` is built from `develop`. `provenance.yml`\n"
        "records which commit each half came from.\n\n"
        "To change the documentation, change `docs/` on the branch it belongs to.\n",
        encoding="utf-8",
    )
    return destination


def validate_composed(tree: Path, tracks: list[Track]) -> None:
    """Check the properties only the composed tree can have.

    Deliberately in Python and not in ``validate_docs.rb``: that validator is
    per-track and reads ``_data``/``_guide``, none of which exist in output, and
    this has to run under a bare ``pytest -q`` on a machine with no Ruby.
    """
    problems: list[str] = []
    by_name = {track.name: track for track in tracks}

    for track in tracks:
        index = tree / track.spec.prefix / "index.html" if track.spec.prefix else tree / "index.html"
        if not index.is_file():
            problems.append(f"{track.name}: no index.html at {index.relative_to(tree)}")

    for required in (".nojekyll", "provenance.yml"):
        if not (tree / required).is_file():
            problems.append(f"missing {required}")

    if (tree / "provenance.yml").is_file():
        recorded = _load_yaml(tree / "provenance.yml").get("tracks", {})
        for name, track in by_name.items():
            got = (recorded.get(name) or {}).get("commit")
            if got != track.commit:
                problems.append(f"provenance.yml records {name} as {got!r}, built {track.commit!r}")

    # Nothing that is tooling rather than content may reach the published tree.
    for leaked in ("Gemfile", "Gemfile.lock", "package.json", "playwright.config.js",
                   "build.py", "generators.yml", "scripts", "vendor", "tests", "node_modules"):
        for found in tree.rglob(leaked):
            problems.append(f"tooling leaked into the site: {found.relative_to(tree)}")

    develop_prefix = TRACKS["development"].prefix
    for page in tree.rglob("*.html"):
        relative = page.relative_to(tree)
        in_develop = relative.parts and relative.parts[0] == develop_prefix
        text = page.read_text(encoding="utf-8", errors="replace")

        has_noindex = 'name="robots"' in text and "noindex" in text
        if in_develop and not has_noindex:
            problems.append(f"development page without noindex: {relative}")
        if not in_develop and has_noindex:
            problems.append(f"stable page carries noindex: {relative}")

        for reference in re.findall(r'(?:href|src)="(/vaft/[^"#?]*)', text):
            target = tree / reference[len("/vaft/"):]
            if target.is_dir():
                target = target / "index.html"
            if not reference.endswith("/") and not target.exists():
                candidate = Path(str(target) + ".html")
                if candidate.exists():
                    continue
            if not target.exists():
                problems.append(f"{relative}: unresolved link {reference}")
        if not in_develop:
            for reference in re.findall(r'href="(/vaft/develop/[^"]*)"', text):
                problems.append(f"stable page links into the development track: {relative} -> {reference}")

    size_mib = sum(p.stat().st_size for p in tree.rglob("*") if p.is_file()) / 1048576
    if size_mib > MAX_SITE_MIB:
        problems.append(f"composed tree is {size_mib:.1f} MiB, over the {MAX_SITE_MIB} MiB ceiling")

    if problems:
        shown = "\n  ".join(sorted(set(problems))[:40])
        raise BuildError(f"composed site failed validation:\n  {shown}")


