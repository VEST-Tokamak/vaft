def _regenerate_only(repo: Path, quiet: bool) -> int:
    """Refresh this checkout's generated _data, for a local preview."""
    docs = repo / "docs"
    generators = declared_generators(docs)
    if not generators:
        print("docs/generators.yml declares no generators", file=sys.stderr)
        return EXIT_FAILED
    head = _git(repo, "rev-parse", "HEAD").stdout.strip()
    branch = _git(repo, "rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    track = Track(
        spec=TRACKS["development"], ref=branch, commit=head,
        commit_date=_git(repo, "show", "-s", "--format=%cI", head).stdout.strip(),
        root=repo, vaft_version=_read_version(repo),
    )
    if not quiet:
        print(f"==> regenerating docs/_data from {branch} ({head[:7]})")
    regenerate_data(track, quiet=quiet)
    write_track_provenance(track)
    if not quiet:
        print("    _data/provenance.yml")
    return EXIT_OK


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Build, validate and publish the VAFT documentation site.",
    )
    parser.add_argument("--stable-ref", default=TRACKS["stable"].default_ref,
                        help="commit-ish for the site root (default: %(default)s)")
    parser.add_argument("--develop-ref", default=TRACKS["development"].default_ref,
                        help="commit-ish for /develop/ (default: %(default)s)")
    parser.add_argument("--track", choices=["both", "stable", "development"], default="both",
                        help="build one track only; cannot be combined with --publish")
    parser.add_argument("--output", type=Path,
                        help="keep the composed tree here instead of a temporary directory")
    parser.add_argument("--publish", action="store_true",
                        help=f"commit and push the composed tree to {PUBLISH_BRANCH}")
    parser.add_argument("--regenerate-only", action="store_true",
                        help="refresh this checkout's docs/_data and exit")
    parser.add_argument("--remote", default="origin")
    parser.add_argument("--branch", default=PUBLISH_BRANCH)
    parser.add_argument("--no-fetch", action="store_true", help="skip `git fetch`")
    parser.add_argument("--keep-temp", action="store_true")
    parser.add_argument("--quiet", action="store_true")
    arguments = parser.parse_args(argv)

    repo = Path(__file__).resolve().parents[1]
    say = (lambda *a: None) if arguments.quiet else print

    try:
        _require("git")
        if arguments.regenerate_only:
            return _regenerate_only(repo, arguments.quiet)

        if arguments.publish and arguments.track != "both":
            print(
                "refusing to publish a single track: the composed tree replaces the whole "
                f"{arguments.branch} branch, so publishing one half would delete the other.",
                file=sys.stderr,
            )
            return EXIT_REFUSED

        if not arguments.no_fetch:
            _git(repo, "fetch", "--no-tags", arguments.remote, "main", "develop", check=False)

        say("==> resolving inputs")
        wanted = ["stable", "development"] if arguments.track == "both" else [arguments.track]
        refs = {"stable": arguments.stable_ref, "development": arguments.develop_ref}
        tracks = [resolve_track(TRACKS[name], refs[name], repo) for name in wanted]
        for track in tracks:
            say(f"    {track.name:<12} {track.ref:<16} {track.commit[:7]}  {track.commit_date}")

        parent = None
        if arguments.publish:
            parent = remote_tip(repo, arguments.remote, arguments.branch)
            say(f"    {arguments.branch} tip {parent[:7]}")

        scratch = Path(tempfile.mkdtemp(prefix="vaft-docs-"))
        try:
            for track in tracks:
                say(f"==> {track.name}: exporting, regenerating, building")
                export_source(track, scratch / "src" / track.name, repo)
                regenerate_data(track, quiet=arguments.quiet)
                write_track_provenance(track)
                build_track(track, scratch / "site" / track.name)
                say(f"    jekyll build{'':<22} {track.pages} pages")
                validate_track(track)
                say(f"    validate_docs.rb{'':<18} passed")

            say("==> composing")
            composed = compose(tracks, scratch / "composed")
            for track in tracks:
                prefix = "/" + (track.spec.prefix + "/" if track.spec.prefix else "")
                say(f"    {prefix:<12} {track.pages} pages from {track.commit[:7]}")

            if arguments.track == "both":
                say("==> validating composed tree")
                validate_composed(composed, tracks)
                say("    links, noindex, tooling and size checks passed")
            else:
                say("==> composed-tree validation skipped (single track)")

            if arguments.output:
                destination = arguments.output.resolve()
                if destination.exists():
                    shutil.rmtree(destination)
                shutil.copytree(composed, destination)
                say(f"    composed tree kept at {destination}")

            if not arguments.publish:
                say("DRY RUN -- nothing published (pass --publish)")
                return EXIT_OK

            say("==> publishing")
            commit = publish(
                composed, repo, parent, _commit_message(tracks),
                remote=arguments.remote, branch=arguments.branch, scratch=scratch,
            )
            say(f"    commit {commit[:7]} (parent {parent[:7]}) pushed to {arguments.branch}")
            say(f"    live shortly at {SITE_URL}/vaft/")
            return EXIT_OK
        finally:
            if arguments.keep_temp:
                say(f"    temporary tree kept at {scratch}")
            else:
                shutil.rmtree(scratch, ignore_errors=True)

    except PublishRace as race:
        print(f"ERROR: {race}", file=sys.stderr)
        return EXIT_RACE
    except ToolchainError as missing:
        print(f"ERROR: {missing}", file=sys.stderr)
        return EXIT_TOOLCHAIN
    except BuildError as failure:
        print(f"ERROR: {failure}", file=sys.stderr)
        print("Nothing was published.", file=sys.stderr)
        return EXIT_FAILED


if __name__ == "__main__":  # pragma: no cover - exercised through the CLI
    raise SystemExit(main())
