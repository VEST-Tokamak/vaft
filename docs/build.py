# publishing
# --------------------------------------------------------------------------


def remote_tip(repo: Path, remote: str, branch: str) -> str:
    result = _git(repo, "ls-remote", remote, f"refs/heads/{branch}")
    line = result.stdout.strip()
    if not line:
        raise BuildError(f"{remote} has no {branch} branch to publish onto")
    return line.split()[0]


def publish(
    tree: Path,
    repo: Path,
    parent: str,
    message: str,
    *,
    remote: str = "origin",
    branch: str = PUBLISH_BRANCH,
    scratch: Path,
) -> str:
    """Commit the composed tree onto ``branch`` and push it, or fail cleanly.

    Built with plumbing against a throwaway index, so no working tree is
    touched and no destructive git command is ever run.  The new commit's
    parent is the tip read before the build started, which makes the push an
    ordinary fast-forward: if anything else published in the meantime, git
    rejects it and nothing is overwritten.
    """
    scratch.mkdir(parents=True, exist_ok=True)
    git_dir = _git(repo, "rev-parse", "--git-common-dir").stdout.strip()
    git_dir = str((repo / git_dir).resolve()) if not os.path.isabs(git_dir) else git_dir

    env = dict(os.environ)
    env["GIT_INDEX_FILE"] = str(scratch / "publish.index")
    env["GIT_DIR"] = git_dir
    env["GIT_WORK_TREE"] = str(tree)

    _run(["git", "add", "--all", "--force", "."], cwd=tree, env=env)
    tree_sha = _run(["git", "write-tree"], cwd=tree, env=env).stdout.strip()

    message_file = scratch / "commit-message"
    message_file.write_text(message, encoding="utf-8")
    commit_env = {k: v for k, v in env.items() if k != "GIT_WORK_TREE"}
    commit = _run(
        ["git", "commit-tree", tree_sha, "-p", parent, "-F", str(message_file)],
        cwd=repo,
        env=commit_env,
    ).stdout.strip()

    pushed = _run(
        ["git", "push", remote, f"{commit}:refs/heads/{branch}"], cwd=repo, check=False
    )
    if pushed.returncode != 0:
        stderr = (pushed.stderr or "") + (pushed.stdout or "")
        if re.search(r"\b403\b|permission|denied|not authorized|read-only", stderr, re.I):
            raise BuildError(
                f"pushing {branch} was refused for lack of permission:\n{stderr.strip()}\n\n"
                "The publish job asks for `contents: write`.  If the organisation forbids "
                "write-scoped workflow tokens, use the deploy-key fallback in docs/README.md: "
                "add a write-enabled deploy key as a secret and point the remote at SSH before "
                "running with --publish."
            )
        if re.search(r"non-fast-forward|fetch first|rejected", stderr, re.I):
            raise PublishRace(
                f"{branch} moved while this build was running.\n"
                f"  expected tip: {parent}\n"
                f"  remote tip:   {remote_tip(repo, remote, branch)}\n"
                f"  built commit: {commit} (created locally, not pushed)\n"
                "Nothing was published. Re-run docs/build.py --publish."
            )
        raise BuildError(f"pushing {branch} failed:\n{stderr.strip()}")
    return commit


def _commit_message(tracks: list[Track]) -> str:
    by_name = {track.name: track for track in tracks}
    stable, development = by_name["stable"], by_name["development"]
    lines = [
        f"docs: publish site (main {stable.commit[:7]}, develop {development.commit[:7]})",
        "",
        f"stable      {stable.ref:<18} {stable.commit}",
        f"development {development.ref:<18} {development.commit}",
        "",
        "Generated by docs/build.py. This branch is output only; see README.md.",
    ]
    run_url = os.environ.get("GITHUB_RUN_URL")
    if run_url:
        lines.append(f"Run {run_url}")
    return "\n".join(lines) + "\n"


