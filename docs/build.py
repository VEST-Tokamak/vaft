def declared_generators(docs: Path) -> list[dict]:
    """What this branch says its documentation is generated from."""
    manifest = docs / "generators.yml"
    if not manifest.is_file():
        return []
    return _load_yaml(manifest).get("generators") or []


def regenerate_data(track: Track, *, quiet: bool = False) -> None:
    """Run the generators the track declares, against the track's own tree."""
    generators = declared_generators(track.docs)
    if not generators:
        raise BuildError(f"{track.name}: docs/generators.yml declares no generators")

    env = dict(os.environ)
    env["PYTHONPATH"] = str(track.root)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env.pop("PYTHONHOME", None)

    for generator in generators:
        module, output = generator["module"], generator["output"]
        target = track.docs / output
        target.parent.mkdir(parents=True, exist_ok=True)
        _run(
            [
                sys.executable, "-m", module,
                "--output", str(target),
                "--provenance-commit", track.commit,
                "--provenance-ref", track.ref,
            ],
            cwd=track.root,
            env=env,
        )
        _verify_generated_from_track(track, target, module)
        track.outputs.append(output)
        if not quiet:
            size = target.stat().st_size
            print(f"    {output:<34} {size:>8,} bytes   source verified")


def _verify_generated_from_track(track: Track, snapshot: Path, module: str) -> None:
    """Prove the generator read *this* tree and not another installed copy.

    ``PYTHONPATH`` normally wins, but an editable install can register a
    meta-path finder that does not care about it.  Every snapshot already
    records a checksum of each source file it describes, so re-deriving those
    checksums from the track's tree turns the snapshot into its own receipt.
    """
    pairs = _declared_sources(snapshot)
    if not pairs:
        raise BuildError(f"{track.name}: {snapshot.name} records no source checksums to verify")
    for relative, recorded in pairs:
        source = track.root / relative
        if not source.is_file():
            raise BuildError(f"{track.name}: {snapshot.name} names a missing source {relative}")
        actual = hashlib.sha256(source.read_bytes()).hexdigest()
        if actual != recorded:
            raise BuildError(
                f"{track.name}: {module} ran against a different tree than {track.commit[:7]}. "
                f"{relative} hashes to {actual[:12]} but the snapshot records {recorded[:12]}."
            )


def write_track_provenance(track: Track) -> Path:
    """Record which tree this track was built from, for the page footer."""
    target = track.docs / "_data" / "provenance.yml"
    target.parent.mkdir(parents=True, exist_ok=True)
    _dump_yaml(
        {
            "schema_version": PROVENANCE_SCHEMA,
            "track": track.name,
            "ref": track.ref,
            "commit": track.commit,
            "short_commit": track.commit[:7],
            "commit_date": track.commit_date,
            "vaft_version": track.vaft_version,
            "generated_at": _now(),
        },
        target,
    )
    return target


